#!/usr/bin/env bash
# One-command LAMMPS MD with a compiled Allegro model (runs inside WSL Ubuntu).
#
#   lammps_md.sh --structure FILE [--model PT2] [--ensemble nve|nvt|npt] [--temp K]
#                [--press bar] [--steps N] [--dt fs] [--nrep n] [--frame i]
#                [--dump-every N] [--thermo N] [--pcouple iso|aniso|tri]
#                [--types "C H"] [--out DIR] [--no-kokkos] [--seed N]
#
# Windows paths (C:\...) are accepted and converted. Output directory gets:
#   in.md            the generated LAMMPS input
#   structure.data   the converted starting structure
#   log.lammps       thermo table, timing
#   traj.lammpstrj   trajectory (open in OVITO)
set -euo pipefail

MODEL=$HOME/pe206/models/base.nequip.pt2
STRUCTURE=""; FRAME=0; NREP=1; ENSEMBLE=nvt; TEMP=300; PRESS=1.0; STEPS=10000; DT=0.5
DUMP_EVERY=100; THERMO=50; PCOUPLE=iso; TYPES="C H"; OUT=""; KOKKOS=1; SEED=12345
while [ $# -gt 0 ]; do
  case "$1" in
    --model) MODEL=$2; shift 2;;      --structure) STRUCTURE=$2; shift 2;;
    --frame) FRAME=$2; shift 2;;      --nrep) NREP=$2; shift 2;;
    --ensemble) ENSEMBLE=$2; shift 2;; --temp) TEMP=$2; shift 2;;
    --press) PRESS=$2; shift 2;;      --steps) STEPS=$2; shift 2;;
    --dt) DT=$2; shift 2;;            --dump-every) DUMP_EVERY=$2; shift 2;;
    --thermo) THERMO=$2; shift 2;;    --pcouple) PCOUPLE=$2; shift 2;;
    --types) TYPES=$2; shift 2;;      --out) OUT=$2; shift 2;;
    --no-kokkos) KOKKOS=0; shift;;    --seed) SEED=$2; shift 2;;
    -h|--help) sed -n 2,15p "$0"; exit 0;;
    *) echo "unknown option $1" >&2; exit 2;;
  esac
done
[ -n "$STRUCTURE" ] || { echo "--structure is required" >&2; exit 2; }

winpath () { case "$1" in [A-Za-z]:*) wslpath -u "$1";; *) echo "$1";; esac; }
STRUCTURE=$(winpath "$STRUCTURE"); MODEL=$(winpath "$MODEL")
[ -n "$OUT" ] && OUT=$(winpath "$OUT") || OUT=$HOME/pe206/md/$(date +%Y%m%d_%H%M%S)_${ENSEMBLE}_${TEMP}K
mkdir -p "$OUT"

export PATH=/usr/local/cuda-13.3/bin:$HOME/.local/bin:$PATH
source "$HOME/.venvs/allegro/bin/activate"
HERE=$(cd "$(dirname "$0")" && pwd)
python "$HERE/to_lammps_data.py" "$STRUCTURE" "$OUT/structure.data" --frame "$FRAME" --types "$TYPES"

DT_PS=$(awk -v d="$DT" 'BEGIN{printf "%.6f", d/1000}')
TDAMP=$(awk -v d="$DT_PS" 'BEGIN{printf "%.6f", 100*d}')
PDAMP=$(awk -v d="$DT_PS" 'BEGIN{printf "%.6f", 1000*d}')
case "$ENSEMBLE" in
  nve) FIX="fix 1 all nve";;
  nvt) FIX="fix 1 all nvt temp $TEMP $TEMP $TDAMP";;
  npt) FIX="fix 1 all npt temp $TEMP $TEMP $TDAMP $PCOUPLE $PRESS $PRESS $PDAMP";;
  *) echo "ensemble must be nve, nvt or npt" >&2; exit 2;;
esac

cat > "$OUT/in.md" <<EOF
# generated by lammps_md.sh
units         metal
atom_style    atomic
boundary      p p p
newton        on
read_data     structure.data
replicate     $NREP $NREP $NREP
pair_style    allegro
pair_coeff    * * $MODEL $TYPES
neighbor      1.0 bin
neigh_modify  every 1 delay 0 check yes
velocity      all create $TEMP $SEED mom yes rot yes dist gaussian
timestep      $DT_PS
$FIX
thermo        $THERMO
thermo_style  custom step time temp pe ke etotal press vol cpu
thermo_modify flush yes
dump          1 all custom $DUMP_EVERY traj.lammpstrj id type x y z vx vy vz
dump_modify   1 sort id
run           $STEPS
EOF

KK=""; [ "$KOKKOS" = 1 ] && KK="-k on g 1 -sf kk -pk kokkos newton on neigh half"
echo "running $ENSEMBLE at $TEMP K, $STEPS steps of $DT fs, output in $OUT"
cd "$OUT"
mpirun -np 1 "$HOME/lammps/build/lmp" $KK -in in.md -log log.lammps -screen none
LOOP=$(grep "Loop time" log.lammps | tail -1)
SECS=$(echo "$LOOP" | awk '{print $4}'); NAT=$(echo "$LOOP" | awk '{print $12}')
MS=$(awk -v s="$SECS" -v n="$STEPS" 'BEGIN{printf "%.2f", 1000*s/n}')
NSDAY=$(grep -A2 "Loop time" log.lammps | tail -3 | grep -m1 Performance | awk '{print $2}')
echo "done: $NAT atoms, $MS ms/step, $NSDAY ns/day"
echo "trajectory: $OUT/traj.lammpstrj   log: $OUT/log.lammps"
[ -d /mnt/c ] && echo "windows path: $(wslpath -w "$OUT")"
